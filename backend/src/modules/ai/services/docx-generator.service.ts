import { Injectable } from '@nestjs/common';
import {
  Document,
  HeadingLevel,
  ImageRun,
  Packer,
  Paragraph,
  TextRun,
} from 'docx';
import { Resvg } from '@resvg/resvg-js';
import { existsSync } from 'node:fs';

const SVG_FALLBACK_PNG_1X1 = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO7Y7j8AAAAASUVORK5CYII=',
  'base64',
);

@Injectable()
export class DocxGeneratorService {
  private readonly preferredFontFiles = [
    '/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf',
    '/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
    '/usr/share/fonts/TTF/DejaVuSans.ttf',
    '/usr/share/fonts/TTF/DejaVuSans-Bold.ttf',
    'C:/Windows/Fonts/arial.ttf',
    'C:/Windows/Fonts/arialbd.ttf',
  ];

  private resolveFontFiles() {
    return this.preferredFontFiles.filter((p) => existsSync(p));
  }

  private normalizeSvgFontStack(svg: string) {
    return svg.replace(
      /font-family="[^"]*"/gi,
      'font-family="Noto Sans, DejaVu Sans, Arial, sans-serif"',
    );
  }

  async generateArchitectureReport(input: {
    title?: string;
    description: string;
    svg: string;
    generatedAt?: Date;
  }): Promise<Buffer> {
    const generatedAt = input.generatedAt ?? new Date();
    const normalizedSvg = this.normalizeSvgFontStack(input.svg);
    const fontFiles = this.resolveFontFiles();
    let pngBuffer: Buffer | null = null;

    try {
      const resvg = new Resvg(normalizedSvg, {
        fitTo: {
          mode: 'width',
          value: 1200,
        },
        font: {
          loadSystemFonts: true,
          fontFiles,
          defaultFontFamily: 'DejaVu Sans',
        },
      });
      pngBuffer = resvg.render().asPng();
    } catch {
      // Keep report generation resilient in environments where SVG rendering can fail.
      pngBuffer = null;
    }

    const descriptionParagraphs = input.description
      .split(/\n\s*\n/g)
      .map((paragraph) => paragraph.trim())
      .filter(Boolean)
      .map((paragraph) => new Paragraph(paragraph));

    const doc = new Document({
      sections: [
        {
          children: [
            new Paragraph({
              text: input.title || 'Architecture Report',
              heading: HeadingLevel.TITLE,
            }),
            new Paragraph({
              children: [
                new TextRun({ text: 'Generated by Thong Thai Space AI Agent' }),
              ],
            }),
            new Paragraph({
              children: [
                new TextRun({ text: `Date: ${generatedAt.toISOString()}` }),
              ],
            }),
            new Paragraph({ text: '' }),
            new Paragraph({
              text: 'Architecture Description',
              heading: HeadingLevel.HEADING_1,
            }),
            ...descriptionParagraphs,
            new Paragraph({ text: '' }),
            new Paragraph({
              text: 'Architecture Diagram',
              heading: HeadingLevel.HEADING_1,
            }),
            new Paragraph({
              children: [
                new ImageRun(
                  pngBuffer
                    ? {
                        type: 'png',
                        data: pngBuffer,
                        transformation: {
                          width: 640,
                          height: 420,
                        },
                      }
                    : {
                        type: 'svg',
                        data: normalizedSvg,
                        fallback: {
                          type: 'png',
                          data: SVG_FALLBACK_PNG_1X1,
                        },
                        transformation: {
                          width: 640,
                          height: 420,
                        },
                      },
                ),
              ],
            }),
          ],
        },
      ],
    });

    return Packer.toBuffer(doc);
  }
}
